"""Low-level MCT block writer.

The first supported capability set is deliberately narrow: geometry, frame
properties, structure groups, supports, and rigid links. Time-history train-load
blocks depend on the confirmed dynamic load path and are layered on top later.
"""

from __future__ import annotations

import math
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path

from vbridge_dyn.core.schemas.bridge import Bridge
from vbridge_dyn.core.schemas.project import Project
from vbridge_dyn.core.schemas.properties import FrameSection, Material

_GRAVITY = 9.806


@dataclass(frozen=True)
class _MctIdMaps:
    material_ids: dict[str, int]
    section_ids: dict[str, int]


def write_base_model_mct(project: Project, path: Path) -> list[str]:
    """Write a base Midas Civil model `.mct` and return generation warnings."""
    bridge = project.bridge
    maps = _build_id_maps(bridge)
    warnings = _collect_warnings(bridge)

    lines: list[str] = []
    _append_header(lines, project)
    _append_nodes(lines, bridge)
    _append_elements(lines, bridge, maps)
    _append_groups(lines, bridge)
    _append_materials(lines, bridge, maps)
    _append_sections(lines, bridge, maps)
    _append_constraints(lines, bridge)
    _append_rigid_links(lines, bridge)
    lines.append("*ENDDATA")
    lines.append("")

    path.write_text("\n".join(lines), encoding="utf-8")
    return warnings


def _build_id_maps(bridge: Bridge) -> _MctIdMaps:
    return _MctIdMaps(
        material_ids={material.id: i for i, material in enumerate(bridge.materials, start=1)},
        section_ids={section.id: i for i, section in enumerate(bridge.sections, start=1)},
    )


def _collect_warnings(bridge: Bridge) -> list[str]:
    warnings: list[str] = []
    if bridge.elastic_links:
        warnings.append("ElasticLinks chưa được export trong MCT v0.2-alpha.")
    if bridge.element_releases:
        warnings.append("ElementRelease chưa được export trong MCT v0.2-alpha.")
    if bridge.nodal_masses:
        warnings.append("NodalMasses chưa được export trong MCT v0.2-alpha.")
    if bridge.distributed_masses:
        warnings.append("DistributedMasses chưa được export trong MCT v0.2-alpha.")
    return warnings


def _append_header(lines: list[str], project: Project) -> None:
    units = project.targets.midas_civil.units
    force = _force_token(units.get("force", "kN"))
    length = _length_token(units.get("length", "m"))
    lines.extend(
        [
            ";---------------------------------------------------------------------------",
            ";  MIDAS/Civil Text(MCT) File.",
            f";  Generated by VBridge-Dyn on {datetime.now().strftime('%Y/%m/%d')}",
            ";---------------------------------------------------------------------------",
            "",
            "*VERSION",
            "   9.1.0",
            "",
            "*UNIT    ; Unit System",
            "; FORCE, LENGTH, HEAT, TEMPER",
            f"   {force:<5}, {length}, J, C",
            "",
            "*PROJINFO    ; Project Information",
            "; PROJECT, REVISION, USER, EMAIL, ADDRESS, TEL, FAX, CLIENT, TITLE, ENGINEER, EDATE",
            f"   PROJECT={_text(project.meta.name)}",
            f"   USER={_text(project.meta.author)}",
            "",
            "*STRUCTYPE    ; Structure Type",
            "; iSTYP, iMASS, iSMAS, bMASSOFFSET, bSELFWEIGHT, GRAV, TEMPER, bALIGNBEAM, bALIGNSLAB, bROTRIGID",
            "     0, 1, 1, NO, NO, 9.806, 0, NO, NO, NO",
            "",
            "*REBAR-MATL-CODE    ; Rebar Material Code",
            "; CONC_CODE, CONC_MDB, SRC_CODE, SRC_MDB",
            " ASTM(RC), Grade 60, ASTM(RC), Grade 60",
            "",
        ],
    )


def _append_nodes(lines: list[str], bridge: Bridge) -> None:
    lines.extend(["*NODE    ; Nodes", "; iNO, X, Y, Z"])
    for node in sorted(bridge.nodes, key=lambda item: item.id):
        lines.append(f" {node.id:>8}, {_num(node.x)}, {_num(node.y)}, {_num(node.z)}")
    lines.append("")


def _append_elements(lines: list[str], bridge: Bridge, maps: _MctIdMaps) -> None:
    lines.extend(
        [
            "*ELEMENT    ; Elements",
            "; iEL, TYPE, iMAT, iPRO, iN1, iN2, ANGLE, iSUB",
        ],
    )
    for element in sorted(bridge.elements, key=lambda item: item.id):
        material_id = maps.material_ids[element.material_id]
        section_id = maps.section_ids[element.section_id]
        element_type = "BEAM" if element.type == "BEAM" else "TRUSS"
        lines.append(
            f" {element.id:>8}, {element_type:<6}, {material_id:>4}, {section_id:>4}, "
            f"{element.n1:>8}, {element.n2:>8}, 0, 0"
        )
    lines.append("")


def _append_groups(lines: list[str], bridge: Bridge) -> None:
    groups = _group_records(bridge)
    if not groups:
        return

    lines.extend(["*GROUP    ; Group", "; NAME, NODE_LIST, ELEM_LIST, PLANE_TYPE"])
    for name, node_ids, element_ids in groups:
        lines.append(f"   {_text(name):<20}, {_id_list(node_ids)}, {_id_list(element_ids)}, 0")
    lines.append("")


def _group_records(bridge: Bridge) -> list[tuple[str, list[int], list[int]]]:
    by_name: dict[str, tuple[set[int], set[int]]] = {}

    def ensure(name: str) -> tuple[set[int], set[int]]:
        if name not in by_name:
            by_name[name] = (set(), set())
        return by_name[name]

    for group in bridge.structure_groups:
        name = group.name or group.id
        node_set, element_set = ensure(name)
        node_set.update(group.node_ids)
        element_set.update(group.element_ids)

    for element in bridge.elements:
        if element.structure_group:
            _, element_set = ensure(element.structure_group)
            element_set.add(element.id)

    records: list[tuple[str, list[int], list[int]]] = []
    for name in sorted(by_name):
        node_set, element_set = by_name[name]
        if node_set or element_set:
            records.append((name, sorted(node_set), sorted(element_set)))
    return records


def _append_materials(lines: list[str], bridge: Bridge, maps: _MctIdMaps) -> None:
    lines.extend(
        [
            "*MATERIAL    ; Material",
            "; iMAT, TYPE, MNAME, SPHEAT, HEATCO, PLAST, TUNIT, bMASS, DAMPRATIO, [DATA1]",
            "; [DATA1] : 2, ELAST, POISN, THERMAL, DEN, MASS",
        ],
    )
    for material in sorted(bridge.materials, key=lambda item: maps.material_ids[item.id]):
        lines.append(_material_line(material, maps.material_ids[material.id]))
    lines.append("")
    lines.extend(
        ["*MATL-COLOR", "; iMAT, W_R, W_G, W_B, HF_R, HF_G, HF_B, HE_R, HE_G, HE_B, bBLEND, FACT"]
    )
    for material in sorted(bridge.materials, key=lambda item: maps.material_ids[item.id]):
        mid = maps.material_ids[material.id]
        lines.append(f" {mid:>4}, 255,   0,   0,    0, 255,   0,    0,   0, 255,  NO, 0.5")
    lines.append("")


def _material_line(material: Material, midas_id: int) -> str:
    elast_kn_m2 = material.E / 1000.0
    unit_weight_kn_m3 = material.rho * _GRAVITY / 1000.0
    mat_type = material.kind if material.kind in {"CONC", "STEEL", "SRC"} else "USER"
    return (
        f" {midas_id:>4}, {mat_type:<5}, {_text(material.name):<18}, 0, 0, , C, NO, "
        f"{_num(material.damping_ratio)}, 2, {_num(elast_kn_m2)}, {_num(material.nu)}, "
        f"{_num(material.alpha_T)}, {_num(unit_weight_kn_m3)}, 0"
    )


def _append_sections(lines: list[str], bridge: Bridge, maps: _MctIdMaps) -> None:
    lines.extend(
        [
            "*SECT-PSCVALUE    ; PSC Value, General Section, Composite PC, Composite General",
            "; SECT=iSEC, TYPE, SNAME, [OFFSET], bSD, bWE, SHAPE, bBU, bEQ",
            ";      AREA, ASy, ASz, Ixx, Iyy, Izz",
            ";      CyP, CyM, CzP, CzM, QyB, QzB, PERI_OUT, PERI_IN, Cy, Cz",
            ";      Y1, Y2, Y3, Y4, Z1, Z2, Z3, Z4",
        ],
    )
    for section in sorted(bridge.sections, key=lambda item: maps.section_ids[item.id]):
        _append_section(lines, section, maps.section_ids[section.id])
    lines.append("")


def _append_section(lines: list[str], section: FrameSection, midas_id: int) -> None:
    asy = section.A if section.Asy is None else section.Asy
    asz = section.A if section.Asz is None else section.Asz
    cy = _section_half_width(section)
    cz = _section_half_depth(section)
    perimeter = 4.0 * (cy + cz)
    lines.extend(
        [
            (
                f"SECT={midas_id:>4}, VALUE     , {_text(section.name):<18}, CC, 0, 0, "
                "0, 0, 0, 0, YES, NO, GEN, YES, YES"
            ),
            (
                f"{_num(section.A)}, {_num(asy)}, {_num(asz)}, {_num(section.J)}, "
                f"{_num(section.Iy)}, {_num(section.Iz)}"
            ),
            (f"{_num(cy)}, {_num(cy)}, {_num(cz)}, {_num(cz)}, 0, 0, {_num(perimeter)}, 0, 0, 0"),
            (
                f"{_num(-cy)}, {_num(cy)}, {_num(cy)}, {_num(-cy)}, "
                f"{_num(cz)}, {_num(cz)}, {_num(-cz)}, {_num(-cz)}"
            ),
        ],
    )


def _section_half_width(section: FrameSection) -> float:
    # Fallback stress points for VALUE/GEN sections when polygon geometry is not yet available.
    return max(math.sqrt(section.Iz / section.A), 0.001)


def _section_half_depth(section: FrameSection) -> float:
    return max(math.sqrt(section.Iy / section.A), 0.001)


def _append_constraints(lines: list[str], bridge: Bridge) -> None:
    if not bridge.supports:
        return
    lines.extend(["*CONSTRAINT    ; Supports", "; NODE_LIST, CONST(Dx,Dy,Dz,Rx,Ry,Rz), GROUP"])
    for support in sorted(bridge.supports, key=lambda item: item.node_id):
        mask = "".join(str(value) for value in support.constraint)
        lines.append(f"   {support.node_id}, {mask}, {_text(support.boundary_group)}")
    lines.append("")


def _append_rigid_links(lines: list[str], bridge: Bridge) -> None:
    if not bridge.rigid_links:
        return
    lines.extend(["*RIGIDLINK    ; Rigid Link", "; M-NODE, DOF, S-NODE LIST, GROUP"])
    for link in sorted(bridge.rigid_links, key=lambda item: item.id):
        lines.append(
            f"   {link.master}, {link.dof_mask}, {_id_list(link.slaves)}, {_text(link.boundary_group)}"
        )
    lines.append("")


def _id_list(values: list[int]) -> str:
    return " ".join(str(value) for value in values)


def _num(value: float) -> str:
    return f"{value:.10g}"


def _text(value: str) -> str:
    return value.replace(",", " ").strip()


def _force_token(value: str) -> str:
    normalized = value.lower()
    if normalized == "kn":
        return "KN"
    if normalized == "n":
        return "N"
    msg = f"Unsupported Midas force unit: {value}"
    raise ValueError(msg)


def _length_token(value: str) -> str:
    normalized = value.lower()
    if normalized == "m":
        return "M"
    if normalized == "mm":
        return "MM"
    msg = f"Unsupported Midas length unit: {value}"
    raise ValueError(msg)
